// @vitest-environment jsdom
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, describe, it, expect } from "vitest";

import {
  DASHBOARD_REGION_SCOPE,
  declaresOnlyCustomProperties,
  installedDrizzleCubeStylesPath,
  parseItems,
  scopeDrizzleCubeStyles,
  splitSelectorList,
} from "../../../sdk-dashboard/scripts/scope-drizzle-cube-styles.mjs";

/**
 * Contract: the stylesheet the shared read-only composition loads for
 * drizzle-cube styles nothing outside the dashboard regions (cinatra#4311).
 *
 * `drizzle-cube/client/styles.css` carries unscoped library rules
 * (`.recharts-*`, `.react-grid-*`, `.react-flow__*`, `.hljs*`) and the
 * application draws Recharts outside dashboards too. The composition, which any
 * host may mount, therefore loads `drizzle-cube-scoped.css`: a copy generated by
 * packages/sdk-dashboard/scripts/scope-drizzle-cube-styles.mjs in which every
 * rule that styles an element is confined to
 * `[data-cinatra-dashboard-shell]` / `[data-cinatra-read-only-composition]`.
 *
 * Pinned here:
 *   1. The committed copy is exactly what the generator makes of the INSTALLED
 *      drizzle-cube stylesheet, so a bump fails until it is regenerated.
 *   2. Structurally, every selector of every styling rule starts with the
 *      region scope; only custom-property-only rules stay unscoped.
 *   3. By behaviour: library and drizzle-cube elements OUTSIDE a region match
 *      no styling rule of the copy, and the same elements inside either region
 *      do (so the check is not vacuous).
 *   4. The composition imports the scoped copy and never the raw stylesheet.
 */

const SDK_COMPONENTS = join(__dirname, "..", "..", "..", "sdk-dashboard", "src", "components");
const SCOPED_CSS = readFileSync(join(SDK_COMPONENTS, "drizzle-cube-scoped.css"), "utf-8");

type Item = { kind: string; prelude?: string; body?: string; text?: string };

/** Every style rule (outside @keyframes/@property), walking into at-rule blocks. */
function styleRules(css: string): Array<{ prelude: string; body: string }> {
  const out: Array<{ prelude: string; body: string }> = [];
  for (const item of parseItems(css) as Item[]) {
    if (item.kind !== "block") continue;
    const prelude = item.prelude ?? "";
    const body = item.body ?? "";
    if (prelude.startsWith("@")) {
      if (/^@(?:-webkit-)?keyframes\b|^@property\b|^@font-face\b/.test(prelude)) continue;
      out.push(...styleRules(body));
    } else {
      out.push({ prelude, body });
    }
  }
  return out;
}

const rules = styleRules(SCOPED_CSS);
const stylingRules = rules.filter((r) => !declaresOnlyCustomProperties(r.body));

afterEach(() => {
  document.body.innerHTML = "";
});

describe("drizzle-cube-scoped.css is the generator's output for the installed drizzle-cube", () => {
  it("matches a fresh generation byte for byte", () => {
    const raw = readFileSync(installedDrizzleCubeStylesPath(join(__dirname, "..", "..", "..", "sdk-dashboard")), "utf-8");
    expect(SCOPED_CSS === scopeDrizzleCubeStyles(raw)).toBe(true);
  });
});

describe("every rule that styles an element is confined to the dashboard regions", () => {
  it("finds styling rules to check (the parse is not empty)", () => {
    expect(stylingRules.length).toBeGreaterThan(500);
  });

  it("prefixes every selector of every styling rule with the region scope", () => {
    const unscoped = stylingRules.flatMap((r) =>
      (splitSelectorList(r.prelude) as string[]).filter((s) => !s.startsWith(`${DASHBOARD_REGION_SCOPE} `)),
    );
    expect(unscoped).toEqual([]);
  });

  it("keeps unscoped only rules that declare nothing but custom properties", () => {
    const unscoped = rules.filter((r) => !r.prelude.startsWith(DASHBOARD_REGION_SCOPE));
    for (const rule of unscoped) {
      expect(declaresOnlyCustomProperties(rule.body), rule.prelude).toBe(true);
    }
  });

  it("refuses a styling rule on the document root rather than emit a broken copy", () => {
    expect(() => scopeDrizzleCubeStyles("html{color:red}")).toThrow();
    expect(() => scopeDrizzleCubeStyles(":root{margin:0}")).toThrow();
    expect(scopeDrizzleCubeStyles(":root{--dc-x:1px}")).toContain(":root{--dc-x:1px}");
  });
});

describe("by behaviour: library elements outside a region match no styling rule", () => {
  /** Elements the upstream file styles, each as an HTML fragment. */
  const PROBES = [
    '<svg class="recharts-surface"></svg>',
    '<div class="recharts-wrapper"><svg><g></g><path></path><rect></rect><circle></circle></svg></div>',
    '<div class="recharts-tooltip-wrapper"></div>',
    '<div class="react-grid-layout"><div class="react-grid-item"><span class="react-resizable-handle react-resizable-handle-se"></span></div></div>',
    '<div class="react-flow"><div class="react-flow__node react-flow__node-default selectable"></div></div>',
    '<pre><code class="hljs language-json"><span class="hljs-keyword"></span></code></pre>',
    '<div class="dashboard-grid-container"></div>',
    '<div class="dc-row-layout"><div class="dc-row-layout-row"></div></div>',
    '<div class="dc:flex dc:items-center dc:p-4 text-dc-text bg-dc-surface"></div>',
  ];

  /** Rules whose selectors jsdom's engine can evaluate (pseudo-elements cannot match an element). */
  function matchingRules(el: Element): string[] {
    const hits: string[] = [];
    for (const rule of stylingRules) {
      for (const selector of splitSelectorList(rule.prelude) as string[]) {
        if (selector.includes("::")) continue;
        try {
          if (el.matches(selector)) hits.push(selector);
        } catch {
          // A selector the test engine cannot parse is still covered by the
          // structural check above; it is not evaluated here.
        }
      }
    }
    return hits;
  }

  function mount(wrapper: string | null): Element[] {
    const host = document.createElement("div");
    if (wrapper) host.setAttribute(wrapper, "true");
    host.innerHTML = PROBES.join("");
    document.body.appendChild(host);
    return [...host.querySelectorAll("*")];
  }

  it("matches nothing outside a region", () => {
    const hits = mount(null).flatMap((el) => matchingRules(el));
    expect(hits).toEqual([]);
  });

  it.each(["data-cinatra-read-only-composition", "data-cinatra-dashboard-shell"])(
    "matches the same elements inside [%s]",
    (region) => {
      const hits = mount(region).flatMap((el) => matchingRules(el));
      expect(hits.some((s) => s.includes(".dashboard-grid-container"))).toBe(true);
      expect(hits.some((s) => s.includes(".react-grid-item"))).toBe(true);
      expect(hits.some((s) => s.includes(".dc\\:flex"))).toBe(true);
    },
  );
});

describe("the composition loads the scoped copy, never the raw stylesheet", () => {
  it("imports no raw drizzle-cube stylesheet", () => {
    const source = readFileSync(join(SDK_COMPONENTS, "read-only-composition.tsx"), "utf-8");
    expect(source).not.toMatch(/drizzle-cube\/client\/styles\.css/);
    expect(source).toMatch(/^import "\.\/drizzle-cube-scoped\.css";$/m);
  });
});
