#!/usr/bin/env node
// Generates `src/components/drizzle-cube-scoped.css`: drizzle-cube's client
// stylesheet with every rule that styles an element confined to the dashboard
// regions (cinatra#4311).
//
// WHY. `drizzle-cube/client/styles.css` is global CSS. Besides its own
// `dc:`-prefixed utilities it carries unscoped library rules (`.recharts-*`,
// `.react-grid-*`, `.react-flow__*`, `.hljs*`, ...). The application also draws
// Recharts outside any dashboard, so the shared read-only composition, which
// any host may mount, must not load those rules globally. It loads this copy
// instead.
//
// THE TRANSFORM. Every style rule that declares anything other than custom
// properties gets each of its selectors prefixed with
//   :where([data-cinatra-dashboard-shell], [data-cinatra-read-only-composition])
// and a descendant combinator. `:where()` adds no specificity, so inside a
// region every rule cascades exactly as the original does. A rule that only
// declares custom properties (`--dc-*`, `--tw-*`, `--xy-*`) is kept as it is:
// a custom property styles nothing by itself, and the theme's `:root`/`.dark`
// overrides read these values from the root. `@keyframes` and `@property` are
// copied unchanged. At-rule blocks (`@layer`, `@media`, `@supports`) are
// walked into. A styling rule whose selector targets the document root
// (`:root`, `html`, `body`, `:host`) cannot be confined this way, so the
// generator refuses it (fail closed) rather than emit a broken copy.
//
// The output is pinned: packages/dashboards/src/__tests__/drizzle-cube-scoped-styles.test.ts
// regenerates it from the installed drizzle-cube and requires byte equality.
//
// Regenerate after a drizzle-cube bump:
//   node packages/sdk-dashboard/scripts/scope-drizzle-cube-styles.mjs

import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const DASHBOARD_REGION_SCOPE =
  ":where([data-cinatra-dashboard-shell], [data-cinatra-read-only-composition])";

const HEADER =
  "/* GENERATED by packages/sdk-dashboard/scripts/scope-drizzle-cube-styles.mjs\n" +
  " * from drizzle-cube/client/styles.css. Do not edit by hand: every rule that\n" +
  " * styles an element is confined to the dashboard regions (cinatra#4311). */\n";

/** Index just past a quoted string starting at `i`. */
function skipString(css, i) {
  const quote = css[i];
  i++;
  while (i < css.length && css[i] !== quote) {
    if (css[i] === "\\") i++;
    i++;
  }
  return i + 1;
}

/** Index of the `}` closing the block whose `{` is at `open`. */
function matchBrace(css, open) {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    const c = css[i];
    if (c === "\\") {
      i++;
      continue;
    }
    if (c === '"' || c === "'") {
      i = skipString(css, i) - 1;
      continue;
    }
    if (c === "/" && css[i + 1] === "*") {
      i = css.indexOf("*/", i + 2) + 1;
      continue;
    }
    if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error(`unbalanced block at ${open}`);
}

/**
 * Split a stylesheet (or block content) into top-level items:
 * { kind: "statement", text } | { kind: "block", prelude, body } | { kind: "comment", text }.
 */
export function parseItems(css) {
  const items = [];
  let i = 0;
  let start = 0;
  while (i < css.length) {
    const c = css[i];
    if (c === "\\") {
      i += 2;
      continue;
    }
    if (c === '"' || c === "'") {
      i = skipString(css, i);
      continue;
    }
    if (c === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2) + 2;
      if (css.slice(start, i).trim() === "") {
        items.push({ kind: "comment", text: css.slice(i, end) });
        start = end;
      }
      i = end;
      continue;
    }
    if (c === ";") {
      const text = css.slice(start, i + 1).trim();
      if (text !== ";") items.push({ kind: "statement", text });
      start = i + 1;
      i++;
      continue;
    }
    if (c === "{") {
      const close = matchBrace(css, i);
      items.push({
        kind: "block",
        prelude: css.slice(start, i).trim(),
        body: css.slice(i + 1, close),
      });
      i = close + 1;
      start = i;
      continue;
    }
    i++;
  }
  const rest = css.slice(start).trim();
  if (rest) items.push({ kind: "statement", text: rest });
  return items;
}

/** Split on top-level commas (outside parens, brackets, strings, escapes). */
export function splitSelectorList(prelude) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < prelude.length; i++) {
    const c = prelude[i];
    if (c === "\\") {
      i++;
      continue;
    }
    if (c === '"' || c === "'") {
      i = skipString(prelude, i) - 1;
      continue;
    }
    if (c === "(" || c === "[") depth++;
    else if (c === ")" || c === "]") depth--;
    else if (c === "," && depth === 0) {
      parts.push(prelude.slice(start, i).trim());
      start = i + 1;
    }
  }
  parts.push(prelude.slice(start).trim());
  return parts.filter(Boolean);
}

/** Property names declared in a style rule body (top level only). */
export function declaredProperties(body) {
  return parseItems(body.endsWith(";") ? body : `${body};`)
    .filter((item) => item.kind === "statement")
    .map((item) => item.text.slice(0, item.text.indexOf(":")).trim())
    .filter(Boolean);
}

/** True when the rule declares only custom properties (styles nothing itself). */
export function declaresOnlyCustomProperties(body) {
  const props = declaredProperties(body);
  return props.length > 0 && props.every((p) => p.startsWith("--"));
}

const ROOT_TARGET = /^(?::root|html|body|:host)(?![\w-])/;

function scopeSelector(selector) {
  if (ROOT_TARGET.test(selector)) {
    throw new Error(`cannot confine a styling rule on the document root: ${selector}`);
  }
  return `${DASHBOARD_REGION_SCOPE} ${selector}`;
}

function transform(css) {
  let out = "";
  for (const item of parseItems(css)) {
    if (item.kind === "comment") continue;
    if (item.kind === "statement") {
      out += item.text;
      continue;
    }
    const { prelude, body } = item;
    if (prelude.startsWith("@")) {
      if (/^@(?:-webkit-)?keyframes\b/.test(prelude) || prelude.startsWith("@property") || prelude.startsWith("@font-face")) {
        out += `${prelude}{${body}}`;
      } else {
        out += `${prelude}{${transform(body)}}`;
      }
      continue;
    }
    if (declaresOnlyCustomProperties(body)) {
      out += `${prelude}{${body}}`;
      continue;
    }
    out += `${splitSelectorList(prelude).map(scopeSelector).join(",")}{${body}}`;
  }
  return out;
}

/** The scoped stylesheet for a drizzle-cube client stylesheet. */
export function scopeDrizzleCubeStyles(css) {
  return `${HEADER}${transform(css)}\n`;
}

const HERE = dirname(fileURLToPath(import.meta.url));
export const SCOPED_STYLES_PATH = join(HERE, "..", "src", "components", "drizzle-cube-scoped.css");

/** The installed drizzle-cube client stylesheet of this package. */
export function installedDrizzleCubeStylesPath(packageRoot = join(HERE, "..")) {
  return join(realpathSync(join(packageRoot, "node_modules", "drizzle-cube")), "dist", "client", "styles.css");
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = process.argv[2] ?? installedDrizzleCubeStylesPath();
  writeFileSync(SCOPED_STYLES_PATH, scopeDrizzleCubeStyles(readFileSync(source, "utf-8")));
  console.log(`wrote ${SCOPED_STYLES_PATH}`);
}
